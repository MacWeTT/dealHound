// Draws the dealHound brand files from one wolf drawing:
//   src/app/icon.svg, favicon.ico, apple-icon.png   the app icon (ink tile, faceted lime wolf)
//   src/components/logo-mark/logo-mark-shapes.ts    the same wolf as data, for the LogoMark component
//   public/brand/logo-{light,dark}.svg              the long logo: icon + "dealHound" as outlines (no font needed)
//   public/fonts/manrope-*.woff2                    the self-hosted font (variable weight)
// The letters are Manrope Bold (SIL Open Font License) turned into outlines.
//
// Run:  npm i --no-save opentype.js @fontsource/manrope @fontsource-variable/manrope && node scripts/generate-brand.mjs && npx prettier --write src/components/logo-mark/logo-mark-shapes.ts
import fs from 'node:fs';
import opentype from 'opentype.js';
import sharp from 'sharp';

const INK = '#111827';
const BRIGHT = { dark: '#65a30d', low: '#a3e635', lime: '#bef264', mid: '#d9f99d', lite: '#ecfccb' };
const SHADED = { dark: '#4d7c0f', low: '#65a30d', lime: '#84cc16', mid: '#84cc16', lite: '#a3e635' };
const LEFT = {
  ear: '126,86 214,150 138,230',
  earIn: '152,134 200,158 154,204',
  fore: '214,150 256,168 256,262 176,236',
  cheekUp: '138,230 214,150 176,236',
  cheek: '110,290 138,230 176,236 256,300',
  jaw: '110,290 256,300 256,430 168,372',
  muzzle: '226,262 256,262 256,430 212,350',
};
const PARTS = [
  ['ear', 'dark'],
  ['earIn', 'low'],
  ['fore', 'lime'],
  ['cheekUp', 'mid'],
  ['cheek', 'low'],
  ['jaw', 'mid'],
  ['muzzle', 'lite'],
];
const FACE = ['232,376 280,376 256,408', '184,232 228,246 190,256', '328,232 284,246 322,256'];

const flip = points => {
  return points
    .split(' ')
    .map(pair => {
      const [x, y] = pair.split(',');

      return `${512 - Number(x)},${y}`;
    })
    .join(' ');
};

// Every polygon of the wolf, left half in light shades and right half mirrored in darker ones.
const wolf = [
  ...PARTS.map(([name, tone]) => {
    return { points: LEFT[name], fill: BRIGHT[tone] };
  }),
  ...PARTS.map(([name, tone]) => {
    return { points: flip(LEFT[name]), fill: SHADED[tone] };
  }),
  ...FACE.map(points => {
    return { points, fill: INK };
  }),
];

// A hairline of the same colour around every facet closes the seams anti-aliasing opens between neighbouring polygons.
const polygons = shapes => {
  return shapes
    .map(({ points, fill }) => {
      return `<polygon points="${points}" fill="${fill}" stroke="${fill}" stroke-width="1.5" stroke-linejoin="round"/>`;
    })
    .join('');
};
const tile = (rx = 112) => {
  return `<rect width="512" height="512" rx="${rx}" fill="${INK}"/>`;
};
const iconSvg = (rx = 112) => {
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 512 512">${tile(rx)}${polygons(wolf)}</svg>`;
};

const write = (file, content) => {
  fs.mkdirSync(file.split('/').slice(0, -1).join('/'), { recursive: true });
  fs.writeFileSync(file, content);
};

// The app icon.
write('src/app/icon.svg', iconSvg());

const png = (svg, size) => {
  return sharp(Buffer.from(svg), { density: 384 }).resize(size, size).png().toBuffer();
};

// iOS rounds the corners itself, so its icon is a plain square.
fs.writeFileSync('src/app/apple-icon.png', await png(iconSvg(0), 180));

// An .ico file is a small header plus the images; modern browsers accept PNG images inside it.
const ico = async sizes => {
  const images = await Promise.all(
    sizes.map(size => {
      return png(iconSvg(), size);
    }),
  );
  const header = Buffer.alloc(6 + images.length * 16);

  header.writeUInt16LE(1, 2);
  header.writeUInt16LE(images.length, 4);

  let offset = header.length;

  images.forEach((image, i) => {
    const entry = 6 + i * 16;
    const size = sizes[i];

    header.writeUInt8(size === 256 ? 0 : size, entry);
    header.writeUInt8(size === 256 ? 0 : size, entry + 1);
    header.writeUInt16LE(1, entry + 4);
    header.writeUInt16LE(32, entry + 6);
    header.writeUInt32LE(image.length, entry + 8);
    header.writeUInt32LE(offset, entry + 12);
    offset += image.length;
  });

  return Buffer.concat([header, ...images]);
};

fs.writeFileSync('src/app/favicon.ico', await ico([16, 32, 48]));

// The wolf as data for the LogoMark component.
write(
  'src/components/logo-mark/logo-mark-shapes.ts',
  `// Generated by scripts/generate-brand.mjs; do not edit by hand.
export const MARK_TILE = '${INK}';

// The wolf alone, cropped to its edges: the home page shows it without the tile.
export const MARK_VIEWBOX = '110 86 292 344';

export const MARK_SHAPES = ${JSON.stringify(wolf)};
`,
);

// The long logo: the icon, then "deal" and "Hound" as outlines.
const bytes = fs.readFileSync('node_modules/@fontsource/manrope/files/manrope-latin-700-normal.woff');
const font = opentype.parse(bytes.buffer.slice(bytes.byteOffset, bytes.byteOffset + bytes.byteLength));

/** Lays text out glyph by glyph with kerning. */
const text = (str, x, y, size) => {
  const unit = font.unitsPerEm;
  let pen = x;
  let previous = null;
  let d = '';

  for (const char of str) {
    const glyph = font.charToGlyph(char);

    if (previous) {
      pen += (font.getKerningValue(previous, glyph) * size) / unit;
    }

    d += glyph.getPath(pen, y, size).toPathData(2);
    pen += (glyph.advanceWidth * size) / unit;
    previous = glyph;
  }

  return { d, advance: pen - x };
};

const HEIGHT = 168;
const SIZE = 150;
const GAP = 28;
const cap = font.charToGlyph('H').getPath(0, 0, SIZE).getBoundingBox().y1 * -1;
const baseline = HEIGHT / 2 + cap / 2;

const logo = ({ ink, accent }) => {
  const deal = text('deal', HEIGHT + GAP, baseline, SIZE);
  const hound = text('Hound', HEIGHT + GAP + deal.advance, baseline, SIZE);
  const width = Math.ceil(HEIGHT + GAP + deal.advance + hound.advance);
  const scale = HEIGHT / 512;

  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="-8 -8 ${width + 16} ${HEIGHT + 16}"><g transform="scale(${scale})">${tile()}${polygons(wolf)}</g><path d="${deal.d}" fill="${ink}"/><path d="${hound.d}" fill="${accent}"/></svg>`;
};

write('public/brand/logo-light.svg', logo({ ink: INK, accent: '#4d7c0f' }));
write('public/brand/logo-dark.svg', logo({ ink: '#f8fafc', accent: '#bef264' }));

// The font: one variable file per script subset (the latin-ext one carries the rupee sign).
for (const subset of ['latin', 'latin-ext']) {
  write(
    `public/fonts/manrope-${subset}.woff2`,
    fs.readFileSync(`node_modules/@fontsource-variable/manrope/files/manrope-${subset}-wght-normal.woff2`),
  );
}

console.log('brand files written');
